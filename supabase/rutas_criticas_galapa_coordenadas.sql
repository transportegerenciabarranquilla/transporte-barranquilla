  valor_secuencia bigint;
begin
  secuencia := pg_get_serial_sequence('public.ruta_criticas', '#');
  if secuencia is not null then
    select max("#") into maximo from public.ruta_criticas;
    execute format('select last_value from %s', secuencia::regclass)
      into valor_secuencia;
    if maximo is not null then
      perform setval(secuencia::regclass, greatest(maximo, valor_secuencia), true);
    end if;
  end if;
end;
$$;

