-- Separe varias advertencias con punto y coma o saltos de linea.
alter table public.ruta_criticas
add column if not exists "ADVERTENCIAS" text not null default '';

comment on column public.ruta_criticas."ADVERTENCIAS" is
'Riesgos conocidos: cables bajos, huecos, inundacion, cierre vial u otros.';

