-- Señales que aparecerán en puntos exactos del mapa.
create table if not exists public.ruta_criticas_riesgos (
  id bigint generated by default as identity primary key,
  ruta text not null,
  tipo text not null default 'peligro'
    check (tipo in ('cables_bajos', 'via_danada', 'inundacion', 'cierre', 'peligro')),
  descripcion text not null,
  latitud double precision not null check (latitud between -90 and 90),
  longitud double precision not null check (longitud between -180 and 180),
  activo boolean not null default true,
  creado_en timestamptz not null default now()
);

alter table public.ruta_criticas_riesgos enable row level security;
grant select, insert, delete on table public.ruta_criticas_riesgos to authenticated;
grant usage, select on sequence public.ruta_criticas_riesgos_id_seq to authenticated;
grant select, insert on table public.ruta_criticas_riesgos to anon;
grant usage, select on sequence public.ruta_criticas_riesgos_id_seq to anon;

drop policy if exists "Riesgos de rutas lectura autenticada" on public.ruta_criticas_riesgos;
create policy "Riesgos de rutas lectura autenticada"
on public.ruta_criticas_riesgos for select to authenticated using (true);

drop policy if exists "Riesgos de rutas escritura autenticada" on public.ruta_criticas_riesgos;
create policy "Riesgos de rutas escritura autenticada"
on public.ruta_criticas_riesgos for insert to authenticated with check (true);

drop policy if exists "Riesgos de rutas eliminacion autenticada" on public.ruta_criticas_riesgos;
create policy "Riesgos de rutas eliminacion autenticada"
on public.ruta_criticas_riesgos for delete to authenticated using (true);

drop policy if exists "Riesgos de rutas lectura publica" on public.ruta_criticas_riesgos;
create policy "Riesgos de rutas lectura publica"
on public.ruta_criticas_riesgos for select to anon using (activo = true);

drop policy if exists "Riesgos de rutas reporte publico" on public.ruta_criticas_riesgos;
create policy "Riesgos de rutas reporte publico"
on public.ruta_criticas_riesgos for insert to anon
with check (activo = true and char_length(descripcion) between 3 and 240);

